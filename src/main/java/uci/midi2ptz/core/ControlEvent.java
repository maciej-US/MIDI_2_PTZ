package uci.midi2ptz.core;

import lombok.AllArgsConstructor;
import lombok.Data;


/**
 * Represents a control event exchanged between application subsystems.
 *
 * <p>A control event is the primary communication object used by the event bus and control framework to propagate user actions,
 * MIDI input events and internally generated system events.</p>
 *
 * <p>Each event contains information about its source, target control panel, action identifier and optional integer value associated
 * with the action.</p>
 *
 * <p>Examples include button presses, encoder rotations, fader movements, camera selection requests and system-generated state changes.</p>
 * <p>The event model intentionally abstracts physical controls from application logic. Regardless of whether an action originates from
 * MIDI hardware, GUI interaction or internal automation, it is represented by the same {@code ControlEvent} structure.</p>
 */
@Data
@AllArgsConstructor
public class ControlEvent {

    /** Defines the origin of a control event.*/
    public enum EventSource {
        MIDI,       /** Event generated by a MIDI controller.*/
        GUI,        /** Event generated by the graphical user interface.*/
        SYSTEM      /** Event generated internally by the application.*/
    }

    /**  Source that generated the event. */
    private EventSource eventSource;

    /**
     * Target control panel associated with the event.
     *
     * <p>This identifies the logical application panel that should process the event.</p>
     */
    private MainControlCore.ControlPanelId panel;

    /**
     * Logical action identifier.
     *
     * <p>The action name describes the operation that should be performed, for example {@code "PAN"}, {@code "TALLY_ON"}, {@code "CAM_SELECT"}
     * or similar application-defined commands.</p>
     */
    private String action;

    /**
     * Numeric value associated with the action.
     *
     * <p>Depending on the event type, this may represent a MIDI value, button state, encoder delta, parameter value or other application-specific payload.</p>
     */
    private int value;
}
