package uci.midi2ptz.midi;

import lombok.Data;

/**
 * Defines a mapping between a MIDI control and a logical application action.
 *
 * <p>A binding describes how a specific MIDI message should be interpreted by the control layer and routed within the
 * application.</p>
 *
 * <p>Bindings are loaded from MIDI configuration files and are used by the MIDI controller subsystem to translate incoming
 * controller events into {@code ControlEvent} instances.</p>
 */
@Data
public class MidiBindingDefinition {

    /**
     * Logical application action assigned to the MIDI control.
     *
     * <p>Examples include camera operations, mode switches, parameter adjustments and other control functions.</p>
     */
    private String action;

    /**
     * Target logical control panel identifier.
     *
     * <p>This value determines which control panel should receive events generated by the associated MIDI control.</p>
     */
    private String panel;

    /**
     * Indicates whether the MIDI control participates in  camera-panel reassignment.
     *
     * <p>Controls marked as reassignable follow the current MIDI panel routing and may operate on different cameras during
     * runtime. Controls with this flag disabled always remain associated with their statically configured panel.</p>
     */
    private boolean reassignable;
}